import { readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const order = [
  'src/shim/extra.mjs', 'src/shim/authors.mjs', 'src/shim/titles.mjs', 'src/shim/archive.mjs',
  'src/shim/patent.mjs', 'src/shim/corporate.mjs', 'src/shim/index.mjs',
  'src/post/markers.mjs', 'src/post/cluster.mjs', 'src/post/bibliography.mjs', 'src/post/index.mjs',
  'src/resolver/gender.mjs',
  'src/styles/build.mjs', 'src/styles/variant.mjs', 'src/styles/stubs.mjs', 'src/styles/samples.mjs',
];
const id = file => `m_${basename(file, '.mjs')}_${basename(dirname(file))}`;
const byBase = new Map(order.map(f => [`${basename(dirname(f))}/${basename(f)}`, f]));

function resolveImport(from, spec) {
  const target = join(dirname(from), spec);
  const key = `${basename(dirname(target))}/${basename(target)}`;
  const found = byBase.get(key);
  if (!found) throw new Error(`unresolved import ${spec} in ${from}`);
  return found;
}

function wrap(file) {
  const exported = [];
  const body = readFileSync(join(root, file), 'utf8')
    .replace(/^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?$/gm, (_, names, spec) => `const {${names}} = ${id(resolveImport(file, spec))};`)
    .replace(/^export\s*\{([^}]*)\}\s*from[^\n]*$/gm, '')
    .replace(/^export\s*\{([^}]*)\};?$/gm, (_, names) => {
      exported.push(...names.split(',').map(s => s.trim()).filter(Boolean));
      return '';
    })
    .replace(/^export\s+(const|function)\s+([A-Za-z0-9_$]+)/gm, (_, kind, name) => {
      exported.push(name);
      return `${kind} ${name}`;
    });
  return `const ${id(file)} = (() => {\n${body}\nreturn { ${[...new Set(exported)].join(', ')} };\n})();\n`;
}

const out = `/* generated by tools/plugin/bundle.mjs from src/; do not edit */\n${order.map(wrap).join('\n')}
var DSTU = Object.assign({}, ${id('src/shim/index.mjs')}, ${id('src/post/index.mjs')}, ${id('src/resolver/gender.mjs')}, ${id('src/styles/build.mjs')}, ${id('src/styles/variant.mjs')}, ${id('src/styles/stubs.mjs')}, ${id('src/styles/samples.mjs')});
`;
writeFileSync(join(root, 'plugin/dstu-lib.js'), out);
console.log(`wrote plugin/dstu-lib.js (${out.length} bytes)`);
